/** The guide of a topic, or null. */
export const guideOf = (lang, topicId) => GUIDES[lang]?.[topicId] || null;

/** Topics the guide page lists, in sidebar order (sub-topics after their parent), with their depth. Word lists are left out. */
export function guideTopics(lang) {
  const out = [];
  const walk = (parent, depth) => {
    for (const tp of childrenOf(lang, parent)) {
      if (groupOf(lang, tp.id) !== 'grammar') continue;
      out.push({ topic: tp, depth });
      walk(tp.id, depth + 1);
    }
  };
  walk(null, 0);
  return out;
}

/** DOM id / URL part of a place in the guide: a topic, a section or a form item. */
export const anchorOf = (topicId, sectionId, form) => [topicId, sectionId, form].filter(Boolean).join('--');

/** The form item of a topic's guide and its section, or null. */
export function itemFor(lang, topicId, form) {
  for (const s of guideOf(lang, topicId)?.sections || []) {
    const item = (s.items || []).find((x) => x.form === form);
    if (item) return { section: s, item };
  }
  return null;
}

/**
 * Where the guide explains a card: { anchor, title } or null when no topic of the card has a guide yet.
 * The form's own item when there is one, else the card's topic (or its nearest parent with a guide).
 */
export function guideAnchor(card) {
  const lang = card?.language;
  if (!LANGS[lang]) return null;
  for (const tp of ancestry(lang, card.topic)) {
    if (!guideOf(lang, tp.id)) continue;
    const form = card.meta?.form;
    const hit = form ? itemFor(lang, tp.id, form) : null;
    if (hit) return { anchor: anchorOf(tp.id, hit.section.id, form), title: formsOf(lang, tp.id)[form] || form };
    return { anchor: anchorOf(tp.id), title: tp.label.replace(/­/g, '') };
  }
  return null;
}

/** {漢字|かんじ} → <ruby> in the guide's own (trusted) HTML. */
export const guideRuby = (html) => html.replace(/\{([^{}|]+)\|([^{}]+)\}/g, '<ruby>$1<rt>$2</rt></ruby>');
